/**
 * Роли акцентного цвета. Компонент получает роль, а конкретный цвет берётся
 * из `tokens.css` по селектору `[data-accent="..."]` — сами компоненты цвета
 * не называют никогда.
 */
export type Accent =
  | "cpu"
  | "gpu"
  | "ram"
  | "storage"
  | "net-down"
  | "net-up"
  | "media"
  | "neutral"
  /* Погода: свои два тона вместо железных ролей — они в вариациях сливаются */
  | "sky-warm"
  | "sky-water"
  | "ok"
  | "warn"
  | "alert"
  | "danger";

/**
 * Цвет шкалы накопителя по остатку свободного места.
 *
 * Единственное место, где цвет говорит не о железе: полоса перестаёт значить
 * «накопитель» и начинает значить «сколько осталось». Правило проекта «цвет
 * закреплён за метрикой» тут нарушается сознательно — забитый диск важнее
 * того, что он диск.
 *
 * Пороги считаются по свободному месту: больше четверти — спокойно, дальше
 * три ступени тревоги. Нижняя граница взята «не меньше пяти», чтобы ровно
 * пять процентов были ещё оранжевыми, а красное начиналось ниже.
 *
 * Датчика нет — возвращаем цвет метрики: у пустой полосы тревожить не о чем.
 */
export function spaceAccent(usedPercent: number | null | undefined): Accent {
  if (usedPercent == null) return "storage";

  const free = 100 - usedPercent;
  if (free > 25) return "ok";
  if (free > 10) return "warn";
  if (free >= 5) return "alert";
  return "danger";
}
