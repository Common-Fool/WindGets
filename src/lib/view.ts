import { useOwnRow } from "./settings";

/*
 * Каким видом карточка себя рисует.
 *
 * ВАЖНО: **вид — не размер, и порогом раскладки его не выразить.** Размер
 * выводится из порогов и всегда меньше полного; вид меняет саму раскладку и
 * бывает больше. У спидтеста «только замер» показывает кольцо вместо графика
 * и требует БОЛЬШЕ высоты, чем обычный вид, — три захода подряд это ломало
 * попытки отличить их по высоте окна.
 *
 * Номер живёт в настройках виджета на стороне Rust и приезжает тем же
 * событием, что и всё остальное: своего хранилища заводить незачем.
 *
 * Меняют вид пунктом «Вид» в меню виджета и на его странице настроек. Левой
 * кнопкой по пустому месту карточки вид листался по кругу до этапа 53 — снято
 * по слову пользователя: половина карточек стала нажимаемой, и промах мимо
 * кнопки перекидывал окно в другой вид.
 */
export function useWidgetView(): number {
  return useOwnRow()?.view ?? 0;
}

/**
 * Чем в карточке служит обложка.
 *
 * Третья ось помимо вида и размера, и живёт она так же — числом в настройках
 * на стороне Rust. Меняют её, как и вид, из меню и из настроек виджета.
 */
/** Компоновка A/B независимо от вида, размера и обложки. */
export function useWidgetLayout(): number {
  return useOwnRow()?.layout ?? 0;
}

export function useWidgetCover(): number {
  return useOwnRow()?.cover ?? 0;
}

/**
 * Номер выбранного размера.
 *
 * Нужен карточке потому, что «сколько всего влезет» решает не порог раскладки,
 * а выбор человека: у трёх раскладок пульта размеры разной формы, и один порог
 * по ширине означал бы в полосе одно, а в квадрате другое. Размер же назван
 * прямо — «Большой», «Средний», — и пункты, которые есть только на больших,
 * привязаны к нему, а не к точкам.
 */
export function useWidgetSize(): number {
  return useOwnRow()?.size ?? 0;
}
