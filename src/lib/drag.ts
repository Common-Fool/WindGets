import { useEffect } from "react";
import { invoke } from "@tauri-apps/api/core";
import { useOwnRow, useSettings } from "./settings";

/**
 * За что окно не тянут: органы управления и выделяемый мышью текст.
 *
 * Проверяется вместе с предками (`closest`), потому что нажатие приходит на
 * самый глубокий элемент — на подпись внутри кнопки, а не на кнопку.
 */
export const KEEPS_THE_MOUSE = "button, input, textarea, select, a, label, [data-no-drag]";

/*
 * ВАЖНО: **запертое поле заметки в этот список не попадает.** Оно занимает всю
 * карточку, и пока правку не разрешили двойным нажатием, мышь до него не
 * доходит вовсе (`pointer-events: none`) — нажатие приходит на карточку под
 * ним, то есть на пустое место, и окно тянется за любой кусок заметки.
 *
 * Так решён спор, которого иначе не разрешить: одна и та же протяжка мышью в
 * поле — это и выделение текста, и перенос окна. Пробовали различать их
 * удержанием, по времени до первого движения; живой проверки это не прошло.
 * Разрешение правки — состояние явное и видимое, и спора в нём нет.
 */

/**
 * Насколько надо увести мышь, чтобы нажатие стало перетаскиванием.
 *
 * Щелчок мышью почти всегда идёт с крошечным сдвигом, и без порога окно
 * трогалось бы с места на каждом нажатии по пустому месту.
 *
 * Порог — только удобство. От зависания приложения спасает не он, а проверка
 * кнопки на стороне Rust (`begin_drag`) и отмена цикла (`end_drag`): между
 * решением «тянем» здесь и приходом `WM_NCLBUTTONDOWN` лежит целый вызов
 * через IPC, и отпустить кнопку в этот зазор проще простого.
 */
const DRAG_THRESHOLD = 4;

/**
 * Окно тянется за любое пустое место карточки.
 *
 * Пришло на смену `data-tauri-drag-region` в шапке: шапки у виджетов больше
 * нет, а другой ручки в окне не было вовсе. Атрибут тут не годится в
 * принципе — Tauri смотрит только на сам элемент под курсором, не на его
 * предков, так что карточка с атрибутом ловила бы мышь на отступах и теряла
 * на любой подписи.
 *
 * Прилипание от этого не страдает: `startDragging` шлёт окну
 * `WM_NCLBUTTONDOWN` с `HTCAPTION`, то есть тот же модальный цикл, в котором
 * работает `snap.rs`. Шапка раньше шла ровно этим же путём.
 *
 * Ставится по разу на окно.
 *
 * Заблокированное положение запирает окна в двух местах сразу: тут мы не
 * начинаем перетаскивание, а Rust снимает окну `WS_THICKFRAME`, отчего оно
 * перестаёт тянуться и за края — полоса захвата из `snap.rs` продолжает
 * отвечать `HTLEFT` и соседями, но `DefWindowProc` не пускает `SC_SIZE`.
 * Окна настроек это не касается — в нём стоит сам выключатель блокировки, и
 * запирать его вместе со всеми значило бы терять от него ключ.
 *
 * Запертость собирается из двух флагов: общего рубильника и своего у виджета.
 * Общий главнее — свой запирает, но отпереть запертое общим не может.
 */
export function useWindowDrag(ignoresLock = false): void {
  const all = useSettings().locked;
  const own = useOwnRow()?.locked === true;
  const locked = (all || own) && !ignoresLock;

  useEffect(() => {
    /*
     * Снимает слушатели прошлого нажатия. Зовётся и при размонтировании, и в
     * начале следующего нажатия.
     *
     * ВАЖНО: **своего `mouseup` нажатие может не получить вовсе.** Начатое
     * перетаскивание уводит мышь в модальный цикл Windows, и отпускание во
     * фронт не приходит — слушатель остаётся висеть. Снимать его обязано
     * следующее нажатие: иначе за сеанс их копится по одному на каждое
     * перетаскивание, и каждый лишний шлёт свой `end_drag` на любой щелчок.
     */
    let release = () => {};

    const grab = (event: MouseEvent) => {
      // Правая кнопка и колесо к перетаскиванию отношения не имеют
      if (event.button !== 0) return;
      if (locked) return;
      if (!(event.target instanceof Element)) return;

      if (event.target.closest(KEEPS_THE_MOUSE) !== null) return;

      release();

      // Экранные координаты, а не координаты окна: окно вот-вот поедет
      const fromX = event.screenX;
      const fromY = event.screenY;

      let started = false;

      const move = (moved: MouseEvent) => {
        const far =
          Math.abs(moved.screenX - fromX) >= DRAG_THRESHOLD ||
          Math.abs(moved.screenY - fromY) >= DRAG_THRESHOLD;
        if (!far) return;

        started = true;
        // Дальше окно ведёт Windows, и мышь нам больше не принадлежит
        document.removeEventListener("mousemove", move);

        // Кнопку проверит Rust: отсюда до сообщения ещё целый вызов
        void invoke("begin_drag").catch(() => {});
      };

      const letGo = () => {
        detach();

        // Отпустили, а перетаскивание, возможно, только начинается: пусть
        // Rust оборвёт цикл, если тот успел начаться без нас
        if (started) void invoke("end_drag").catch(() => {});
      };

      /*
       * Именно `letGo`, а не то, что лежит в `release`: к этому мгновению
       * переменную успевает перехватить следующее нажатие, и снималось бы
       * тогда чужое, а своё оставалось бы навсегда.
       */
      const detach = () => {
        document.removeEventListener("mousemove", move);
        document.removeEventListener("mouseup", letGo);
        release = () => {};
      };

      release = detach;

      document.addEventListener("mousemove", move);
      document.addEventListener("mouseup", letGo);
    };

    document.addEventListener("mousedown", grab);
    return () => {
      document.removeEventListener("mousedown", grab);
      release();
    };
  }, [locked]);
}
