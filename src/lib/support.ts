import type { Key } from "./i18n";
import ways from "./support.json";

/**
 * Способы поддержать проект — раздел «Поддержать» в окне настроек.
 *
 * Новый способ — одна запись в `support.json` и строка его пояснения в
 * каталоге. Имена площадок — имена собственные и не переводятся; у
 * криптовалюты своего имени нет, и она берёт его из каталога.
 *
 * Список лежит в JSON, а не здесь, потому что его читает и Rust: напоминание
 * о донатах (`support_reminder.rs`) не всплывает, пока ни у одного способа
 * нет ссылки, — звать поддержать некуда. Один файл на двоих — значит, они не
 * разойдутся. Ключи каталога в нём сверяет тест
 * `support_ways_name_real_catalog_keys`: типом их тут уже не проверить.
 *
 * `value` пуст — ссылку или адрес ещё не дали: кнопка погашена, а под ней
 * сказано, что ссылка появится позже. Заглушка честнее выдуманной ссылки.
 */
export type SupportWay = {
  id: string;
  /** Имя площадки — имя собственное, не переводится. */
  name?: string;
  /** Имя из каталога — у кого собственного имени нет. */
  nameKey?: Key;
  /** `link` открывается в браузере, `copy` — адрес, который копируют. */
  kind: "link" | "copy";
  value: string;
  /** Строка под именем: что это и как работает. */
  about: Key;
  /**
   * QR той же ссылки — строки модулей, «1» тёмный. Матрицей, а не картинкой:
   * SVG из неё чёткий на любом масштабе и не тянет файл в сборку. Снята с
   * QR, который дал Monobank, и сверена декодером с `value` — правится только
   * вместе со ссылкой.
   */
  qr?: string[];
};

export const SUPPORT_WAYS = ways as SupportWay[];
