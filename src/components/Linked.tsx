import { openLink, pieces } from "../lib/links";
import "./Linked.css";

/**
 * Текст, в котором ссылки нажимаются.
 *
 * Один на заметки и на дела: и там, и там текст пишет человек, и ссылка в нём —
 * это ссылка, а не набор букв.
 *
 * Ссылка бывает двух видов: голая, где видно сам адрес, и со своим словом,
 * пришедшая из письма, — там видно слово, а адрес прячется и всплывает
 * подсказкой при наведении. Разбирает обе `pieces` в `lib/links.ts`.
 *
 * ВАЖНО: **это не `<a href>`.** Настоящая ссылка увела бы само окно виджета на
 * страницу — webview тут один и без адресной строки, вернуться из него было бы
 * нечем. Открывает браузер Rust отдельным процессом, а сюда попадает только
 * нажатие.
 */
type Props = {
  text: string;
  /**
   * Ссылки нажимаются прямо сейчас.
   *
   * Гасятся они там, где текст правят: в поле заметки под курсором нажатие
   * должно ставить курсор, а не открывать браузер. Заодно это и есть ответ на
   * вопрос «как поставить курсор внутрь ссылки» — выйти из чтения в правку.
   */
  live?: boolean;
  /**
   * Ссылку со своим словом показывать всей записью, а не словом. Нужно
   * подложке заметки: буквы под прозрачным полем обязаны совпадать с полем
   * знак в знак, иначе курсор, выделение и перенос строк расходятся с текстом.
   */
  verbatim?: boolean;
};

export function Linked({ text, live = true, verbatim = false }: Props) {
  return (
    <>
      {pieces(text, verbatim).map((piece, at) =>
        piece.link ? (
          <span
            key={at}
            className="link"
            data-live={live}
            title={piece.href}
            onClick={(event) => {
              if (!live) return;
              // Нажатие по ссылке — это только ссылка: у строки дела на нём
              // висит переключение галочки
              event.stopPropagation();

              // Второе нажатие пары браузер не открывает: двойным по ссылке
              // открывают правку строки, а не две одинаковые вкладки
              if (event.detail > 1) return;
              openLink(piece.href);
            }}
            /*
             * ВАЖНО: **двойное нажатие гасится отдельно.** Одиночные до строки
             * не доходят, а двойное дошло бы — и обработчик строки, уверенный,
             * что галочку уже перевернули дважды, перевернул бы её один раз.
             */
            onDoubleClick={(event) => {
              if (live) event.stopPropagation();
            }}
          >
            {piece.text}
          </span>
        ) : (
          <span key={at}>{piece.text}</span>
        ),
      )}
    </>
  );
}
