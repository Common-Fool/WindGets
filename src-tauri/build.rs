fn main() {
    // tauri-build следит за конфигом и ресурсами бандла, но не за ICO.
    // Без этого Cargo повторно использовал старый .res после замены значка.
    println!("cargo:rerun-if-changed=icons/icon.ico");
    // Манифест сборочный скрипт и так видит через include_str!, но строка
    // выше отключает Cargo слежку по умолчанию — пусть зависимость будет явной
    println!("cargo:rerun-if-changed=app.manifest");

    // Свой манифест вместо умолчаний tauri-build: приложению нужны права
    // администратора, иначе не читаются накопители, Super I/O платы и Tctl/Tdie
    // процессора — из 233 датчиков доходит 115 (замер,
    // этап 16). UAC при этом спрашивают только на ручном запуске: автозапуск
    // идёт задачей планировщика с наивысшими правами, см. `src/autostart.rs`.
    //
    // ВАЖНО: свой манифест **заменяет** манифест tauri-build целиком, поэтому
    // всё, что было в нём, надо повторить. Забытая зависимость от
    // Microsoft.Windows.Common-Controls 6.0 роняет приложение при запуске с
    // «STATUS_ENTRYPOINT_NOT_FOUND» (0xc0000139): без неё грузится comctl32
    // пятой версии, где нет функций, которые импортирует tao. Выглядит это как
    // испорченная сборка, а не как неполный манифест. Блок windowsSettings нужен
    // по той же причине: без PerMonitorV2 окна размывались бы на мониторе с
    // другим масштабом.
    //
    // ВАЖНО: **комментариев внутри app.manifest быть не должно.** С ними Windows
    // отказывается запускать exe с «неправильной параллельной конфигурацией»
    // (os error 14001). Поймано бисекцией: любой состав манифеста без
    // комментариев принимается, с комментариями — никакой. Поэтому объяснение
    // живёт здесь.
    let windows = tauri_build::WindowsAttributes::new().app_manifest(include_str!("app.manifest"));

    tauri_build::try_build(tauri_build::Attributes::new().windows_attributes(windows))
        .expect("сборка Tauri не удалась");
}
