    /// Кегль карточки в точках при 100 %: от него считается `em` в порогах
    /// `@container`. Берём из самих токенов, а не числом: разойдись эти две
    /// величины — и все размеры промахнутся мимо своих порогов молча.
    fn card_em() -> f64 {
        const TOKENS: &str = include_str!("../../src/styles/tokens.css");

        // `--text-md: calc(15px * var(--scale));`
        let line = TOKENS
            .lines()
            .find(|line| line.trim_start().starts_with("--text-md:"))
            .expect("в токенах есть --text-md");
        let number = line
            .split("calc(")
            .nth(1)
            .and_then(|tail| tail.split("px").next())
            .expect("значение вида calc(15px * ...)");

        number.trim().parse().expect("кегль числом")
    }

    /// Рамка карточки с обеих сторон: контейнер порогов — это содержимое
    /// `.card`, то есть окно без её бордюра в точку.
    const CARD_BORDER: f64 = 2.0;

    /// ВАЖНО: **размер обязан быть строго УЖЕ своего порога, а не равен ему.**
    ///
    /// Условие в CSS — `width < N em`, и на равенстве оно не срабатывает.
    /// Ширины сперва были посчитаны как «порог плюс рамка», то есть ровно по
    /// границе: на кегле 0.9 их спасало округление до целых точек, а на 100 %
    /// и выше блок, который должен уйти, оставался на месте. Поймать это
    /// глазами нельзя — окно встаёт нужной ширины, просто ничего не прячет.
    #[test]
    fn presets_really_trip_their_threshold() {
        let em = card_em();

        for scale in [
            settings::MIN_SCALE,
            settings::DEFAULT_SCALE,
            settings::MAX_SCALE,
        ] {
            for widget in WIDGETS {
                for preset in preset_sets(widget).into_iter().flatten() {
                    // То же по высоте: вид «только замер» держится ровно тем,
                    // что окно ниже порога, на котором уходит график
                    if let (Some(below), Some(height)) = (preset.below_height, preset.height) {
                        let container = height * scale - CARD_BORDER;
                        let threshold = below * em * scale;
                        assert!(
                            container < threshold,
                            "у «{}» размер «{}» при кегле {scale} выше порога {below}em",
                            widget.id,
                            preset.name
                        );
                    }

                    // И обратная ловушка: размер, нечаянно опущенный под свой
                    // порог, молча теряет раскладку. У паролей так провалился
                    // полный размер, у сети пропали подписи
                    if let (Some(keeps), Some(height)) = (preset.keeps, preset.height) {
                        let container = height * scale - CARD_BORDER;
                        let threshold = keeps * em * scale;
                        assert!(
                            container > threshold,
                            "у «{}» размер «{}» при кегле {scale} падает под порог {keeps}em",
                            widget.id,
                            preset.name
                        );
                    }

                    let Some(below) = preset.below else {
                        continue;
                    };

                    let container = preset.width * scale - CARD_BORDER;
                    let threshold = below * em * scale;

                    assert!(
                        container < threshold,
                        "у «{}» размер «{}» при кегле {scale} даёт контейнер {container},                          а порог {below}em это {threshold}: блок не уйдёт",
                        widget.id,
                        preset.name
                    );
                }
            }
        }
    }

