    /// Есть ли что переключать у обложки при этом виде.
    pub fn switches_covers(&self, view: usize) -> bool {
        self.covers.len() > 1 && !self.covers_hidden.contains(&view)
    }

    /// Есть ли что переключать. Один вид и ни одного — одно и то же.
    pub fn switches_views(&self) -> bool {
        self.views.len() > 1
    }

    /// На сколько точек вид меняет высоту окна при кегле 100 %.
    ///
    /// Незнакомый номер вида поправки не получает: настройки правят руками, и
    /// окно от этого не должно ни съёживаться, ни распухать.
    pub fn view_shift(&self, view: usize) -> f64 {
        self.view_heights.get(view).copied().unwrap_or(0.0)
    }

    /// Ниже этого окно тянуть не дадим.
    ///
    /// Общий пол намеренно далёк от размера по содержимому: узкую карточку
    /// пользователь выбирает сам, а вот окно в три точки — это уже промах
    /// мышью, от которого раскладку не восстановить.
    ///
    /// У кого раскладка ниже своего числа перестаёт расступаться и начинает
    /// резаться, тот держит собственный предел в [`Widget::floor`].
    pub fn min_size(&self, scale: f64) -> LogicalSize<f64> {
        let (width, height) = self.floor.unwrap_or((MIN_WIDTH, MIN_HEIGHT));
        LogicalSize::new(width * scale, height * scale)
    }
